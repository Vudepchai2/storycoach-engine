from __future__ import annotations

import os
from pathlib import Path

from .bank import Bank
from .recall import _by_date, gaps, observation_line, GAP_ORDER

HEADER = "<!-- Generated by the coach from log.jsonl. Don't edit; tell the coach instead. -->"


def _obs_section(bank: Bank, about: str) -> list[str]:
    obs = [o for o in bank.live("observation") if o["data"].get("about") == about]
    return [observation_line(o) for o in obs] or ["- none"]


def _profile(bank: Bank, name: str) -> list[str]:
    return [f"# {name}", "", "## Themes", *_obs_section(bank, "person"),
            "", "## How they tell it", *_obs_section(bank, "telling")]


def _timeline(bank: Bank) -> list[str]:
    lines = ["# Timeline"]
    moments = _by_date(bank.live("moment"))
    for m in moments:
        d = m["data"]
        lines += ["", f"## [{m['id']}] {d.get('title', '')}", f"- status: {bank.moment_status(m['id'])}"]
        if d.get("when"):
            lines.append(f"- when: {d['when']}")
        if d.get("where"):
            lines.append(f"- where: {d['where']}")
        names = [bank.records[w]["data"].get("name", w) for w in d.get("who") or []
                 if w in bank.records]
        if names:
            lines.append(f"- who: {', '.join(names)}")
        for f in ("what_happened", "what_changed", "meaning"):
            if d.get(f):
                lines.append(f"- {f}: {d[f]}")
        for q in d.get("quotes") or []:
            lines.append(f'- quote: "{q}"')
    if not moments:
        lines += ["", "- none"]
    return lines


def _people(bank: Bank) -> list[str]:
    lines = ["# People"]
    people = bank.live("entity")
    for e in people:
        d = e["data"]
        lines += ["", f"## [{e['id']}] {d.get('name', '')}", f"- kind: {d.get('kind', '')}"]
        if d.get("relation"):
            lines.append(f"- relation: {d['relation']}")
        if d.get("aliases"):
            lines.append(f"- aliases: {', '.join(d['aliases'])}")
        appears = [m for m in bank.live("moment") if e["id"] in (m["data"].get("who") or [])]
        if appears:
            lines.append("- moments: " + ", ".join(f"[{m['id']}] {m['data'].get('title', '')}"
                                                   for m in appears))
    if not people:
        lines += ["", "- none"]
    return lines


def _proof(bank: Bank) -> list[str]:
    lines = ["# Proof"]
    claims = [r for r in bank.records.values() if r["type"] == "claim"]
    for c in claims:
        d = c["data"]
        status = bank.claim_status(c["id"])
        flag = f" (retracted: {c['retracted']})" if c["retracted"] else ""
        lines += ["", f"## [{c['id']}] {d.get('about', '')}.{d.get('key', '')}: "
                      f"{d.get('statement', '')} · {status}{flag}"]
        for s in c["sources"]:
            quote = s.get("quote")
            lines.append(f"- {s.get('kind', '')} {s.get('ref', '')}"
                         + (f': "{quote}"' if quote else ""))
        if not c["sources"]:
            lines.append("- no sources")
    if not claims:
        lines += ["", "- none"]
    return lines


def _open(bank: Bank) -> list[str]:
    lines = ["# Open", "", "## Open conflicts"]
    open_ = [c for c in bank.conflicts.values() if c["open"]]
    for c in open_:
        vals = " vs ".join(f"{cid}={bank.records[cid]['data'].get('value')}" for cid in c["claims"])
        lines.append(f"- [{c['id']}] {c['about']}.{c['key']}: {vals}")
    if not open_:
        lines.append("- none")
    found = gaps(bank)
    for g in GAP_ORDER:
        items = [x for x in found if x["gap"] == g]
        if items:
            lines += ["", f"## Gap: {g}", f"Ask in: {items[0]['question_section']}"]
            lines += [f"- [{x['id']}] {x['detail']}" for x in items]
    return lines


def write_pages(bank: Bank, name: str, out_dir: Path) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pages = {
        "profile.md": _profile(bank, name),
        "timeline.md": _timeline(bank),
        "people.md": _people(bank),
        "proof.md": _proof(bank),
        "open.md": _open(bank),
    }
    paths = []
    for fname, body in pages.items():
        path = out_dir / fname
        tmp = out_dir / f"{fname}.tmp"
        tmp.write_text("\n".join([HEADER, "", *body]) + "\n", encoding="utf-8", newline="\n")
        os.replace(tmp, path)
        paths.append(path)
    return paths
