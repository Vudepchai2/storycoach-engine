import pytest

from storycoach.memory import create_bank, open_bank
from storycoach.memory.pages import write_pages
from storycoach.memory.retain import retain
from storycoach.memory.sources import import_source

HEADER = "<!-- Generated by the coach from log.jsonl. Don't edit; tell the coach instead. -->"
SAID = {"kind": "said", "ref": "sessions/a"}
TRANSCRIPT = {"kind": "transcript", "ref": "takes/take1.txt"}
NAMES = ["profile.md", "timeline.md", "people.md", "proof.md", "open.md"]


def run(store, items, source=SAID):
    return retain(store, {"source": source, "items": items})


@pytest.fixture
def built(tmp_path):
    directory = create_bank(tmp_path, "Ana")
    store = open_bank(directory)[0]
    run(store, [
        {"type": "entity", "name": "Lee", "kind": "person", "relation": "co-founder"},
        {"type": "moment", "title": "Pilot launch", "when": "May 2025", "where": "Leeds",
         "who": ["Lee"], "what_happened": "We converted builders", "quotes": ["we did it"]},
        {"type": "claim", "about": "m1", "key": "leads", "statement": "100 leads",
         "value": 100, "quote": "a hundred"},
        {"type": "claim", "about": "m1", "key": "team", "statement": "team of 3",
         "value": 3, "quote": "three of us"},
    ])
    run(store, [{"type": "claim", "about": "m1", "key": "leads", "statement": "100 leads",
                 "value": 100, "quote": "100 it was"}], TRANSCRIPT)
    run(store, [{"type": "claim", "about": "m1", "key": "team", "statement": "team of 5",
                 "value": 5, "quote": "five"}])
    run(store, [{"type": "observation", "about": "telling", "statement": "Rushes the end"}])
    return directory, open_bank(directory)[1]


def test_pages_written_with_header(built, tmp_path):
    directory, bank = built
    paths = write_pages(bank, "Ana", directory / "pages")
    assert [p.name for p in paths] == NAMES
    for p in paths:
        assert p.read_text(encoding="utf-8").splitlines()[0] == HEADER
    proof = (directory / "pages" / "proof.md").read_text(encoding="utf-8")
    assert "corroborated" in proof and "takes/take1.txt" in proof
    assert "Rushes the end" in (directory / "pages" / "profile.md").read_text(encoding="utf-8")
    assert "x1" in (directory / "pages" / "open.md").read_text(encoding="utf-8")


def test_pages_rewritten_not_appended(built):
    directory, bank = built
    out = directory / "pages"
    write_pages(bank, "Ana", out)
    first = {p.name: p.stat().st_size for p in out.iterdir()}
    write_pages(bank, "Ana", out)
    assert {p.name: p.stat().st_size for p in out.iterdir()} == first
    assert set(first) == set(NAMES)


def test_pages_creates_out_dir(built, tmp_path):
    _, bank = built
    write_pages(bank, "Ana", tmp_path / "new" / "pages")
    assert (tmp_path / "new" / "pages" / "open.md").exists()


def test_import_source_dedupes_by_hash(tmp_path):
    directory = create_bank(tmp_path, "Ana")
    cv = tmp_path / "cv.txt"
    cv.write_text("my cv", encoding="utf-8")
    assert import_source(directory, cv) == ("s1", True)
    assert import_source(directory, cv) == ("s1", False)
    assert len(list((directory / "sources").iterdir())) == 1
    events = open_bank(directory)[0].events()
    assert len(events) == 1
    data = events[0]["data"]
    assert data["filename"] == "cv.txt"
    assert data["stored"] == f"sources/{data['sha256'][:12]}-cv.txt"
    store = open_bank(directory)[0]
    run(store, [{"type": "entity", "name": "A", "kind": "person"}],
        {"kind": "document", "ref": "s1"})


def test_import_source_missing_file(tmp_path):
    directory = create_bank(tmp_path, "Ana")
    with pytest.raises(FileNotFoundError, match="nope.txt"):
        import_source(directory, tmp_path / "nope.txt")
